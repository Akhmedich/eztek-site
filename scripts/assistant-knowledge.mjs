// Builds the website assistant's reference text from src/data, keeping only facts it may state:
// confirmed company details and the general service, building and area copy. Prices, hours,
// licenses, ratings, response times and other PLACEHOLDER values are left out on purpose.
// npm run assistant:knowledge          writes supabase/functions/assistant/knowledge.ts
// npm run assistant:knowledge -- --check   fails if that file is out of date (CI)
import { readFileSync, writeFileSync } from 'node:fs';

const data = (f) => import(new URL(`../src/data/${f}`, import.meta.url));
const { company } = await data('company.ts');
const { SERVICES } = await data('services.ts');
const { BUILDINGS } = await data('buildings.ts');
const { AREAS } = await data('areas.ts');

// FAQ answers that promise care plan benefits or insurance paperwork: plan contents and insurance
// are PLACEHOLDER in plans.ts and company.ts, so the assistant must not repeat them
const UNCONFIRMED = /plan clients|plans include|\bCOIs?\b|insurance/i;
const faq = (f) => (UNCONFIRMED.test(f.q + f.a) ? [] : [`Q: ${f.q} A: ${f.a}`]);

const a = company.address;
const lines = [
  '# Company (confirmed)',
  `${company.name}, in business since ${company.founded}. Office: ${a.street}, ${a.city}, ${a.region} ${a.zip} (${a.hood}). Phone: ${company.phoneDisplay}.`,
  'Low-voltage systems integrator for residential, commercial, multifamily, educational and institutional properties in New York City.',
  '',
  '# Website pages',
  '/quote/ Get a quote: four short steps, shows a typical installed price range, books a free site survey in NYC, accepts photos and plans.',
  '/service/ Request service for an existing system. /care-plans/ Maintenance care plans. /portal/ Client login. /contact/ Contact. /partners/ For contractors and architects.',
  '',
  '# Services',
  ...SERVICES.flatMap((s) => [
    `## ${s.name} (/services/${s.slug}/)`,
    s.desc,
    s.intro,
    `Includes: ${s.includes.join('; ')}.`,
    `Signs it is time: ${s.signs.join('; ')}.`,
    ...s.faqs.flatMap(faq),
  ]),
  '',
  '# Building types (/buildings/)',
  ...BUILDINGS.flatMap((b) => [
    `## ${b.name} (/buildings/${b.slug}/)`,
    `For: ${b.who}`,
    b.intro,
    `Typical needs: ${b.needs.join('; ')}.`,
    ...b.faqs.flatMap(faq),
  ]),
  '',
  '# Areas served (/areas/)',
  ...AREAS.map((r) => `${r.name}: ${r.note} Neighborhoods include ${r.hoods.join(', ')}.`),
];

const out = `// Generated by scripts/assistant-knowledge.mjs from src/data. Do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(lines.join('\n'))};\n`;
const target = new URL('../supabase/functions/assistant/knowledge.ts', import.meta.url);
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(target, 'utf8'); } catch { /* missing */ }
  if (cur !== out) { console.error('supabase/functions/assistant/knowledge.ts is out of date: npm run assistant:knowledge'); process.exit(1); }
  console.log('assistant knowledge is up to date');
} else {
  writeFileSync(target, out);
  console.log(`wrote knowledge.ts (${out.length} chars)`);
}
